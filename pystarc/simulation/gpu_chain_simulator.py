"""
Batch GPU Brownian-dynamics simulator for one flexible chain and one rigid target.

Each trajectory evolves three coupled motions in the target-centered frame:
rigid-body translation of the chain center of mass, rigid-body rotation of the
chain orientation quaternion, and internal-coordinate Brownian dynamics of the
coarse-grained chain beads on the smaller substep dt_chain. Active trajectories
occupy a fixed-capacity slot pool on the GPU; finished trajectories are retired
into their canonical index order and replaced immediately from the remaining
queue until all requested trajectories complete.

All random numbers are generated by counter-based Philox4x32-10 streams keyed on
(seed, trajectory_id, outer_step, stream_id, draw_index), so every trajectory is
invariant to batch size, slot assignment, and execution order.
"""

